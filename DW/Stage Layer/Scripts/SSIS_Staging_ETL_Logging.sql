/*
-------------------------------------------------------------------------------
TASK: Log Batch Start
PACKAGE: stg_load_execute

PURPOSE:
- Creates a new record in dbo.etl_batch_log.
- Generates a new batch_id.
- Returns the generated batch_id to SSIS.

OLE DB PARAMETER MAPPING:
    Parameter 0: User::batch_id (Int64 / LONG)

NOTE:
The SELECT statement returns the identity generated by the INSERT.
SCOPE_IDENTITY() must be executed in the same SQL session.
-------------------------------------------------------------------------------
*/

INSERT INTO dbo.etl_batch_log
(
    start_date
)
VALUES
(
    GETDATE()
);


SET ? = SCOPE_IDENTITY();


/*
-------------------------------------------------------------------------------
TASK: Log Batch End
PACKAGE: stg_load_execute

PURPOSE:
- Checks whether the current batch has execution log records.
- Marks the batch as Failed if:
    1. No execution records exist for the batch.
    2. At least one operation has is_success <= 0.
- Otherwise, marks the batch as Succeeded.
- Records the batch end time.

OLE DB PARAMETER MAPPING:
    Parameter 0: User::batch_id (Int64 / LONG)
    Parameter 1: User::batch_id (Int64 / LONG)
    Parameter 2: User::batch_id (Int64 / LONG)
    Parameter 3: User::batch_id (Int64 / LONG)

IMPORTANT:
The same SSIS variable is mapped four times because each ? represents
a separate positional parameter.
-------------------------------------------------------------------------------
*/

IF NOT EXISTS
(
    SELECT 1
    FROM dbo.etl_execution_log
    WHERE batch_id = ?
)
OR EXISTS
(
    SELECT 1
    FROM dbo.etl_execution_log
    WHERE batch_id = ?
      AND is_success <= 0
)
BEGIN
    UPDATE dbo.etl_batch_log
    SET status = 'Failed',
        end_date = GETDATE()
    WHERE batch_id = ?;
END
ELSE
BEGIN
    UPDATE dbo.etl_batch_log
    SET status = 'Succeeded',
        end_date = GETDATE()
    WHERE batch_id = ?;
END;


