
/*
===============================================================================
SSIS STAGING ETL PROJECT
===============================================================================

PACKAGE STRUCTURE
-----------------
1. Parent Package:
   stg_load_execute

   Responsibilities:
   - Create a new ETL batch.
   - Store the generated batch_id in User::batch_id.
   - Execute the child packages for each staging table.
   - Update the final batch status.

2. Child Packages:
   One package for each staging table.

   Responsibilities:
   - Truncate the target staging table.
   - Log truncate success or failure.
   - Load data into the staging table.
   - Log insert success or failure.

LOGGING TABLES
--------------
dbo.etl_batch_log
    Stores the overall ETL batch execution information.

dbo.etl_execution_log
    Stores the result of each operation for each table.

IMPORTANT
---------
- The SQL statements below use OLE DB placeholders (?).
- Parameter Mapping uses positional indexes: 0, 1, 2, ...
- The parameters must be mapped in exactly the same order.
- The script is documentation for SSIS Execute SQL Tasks.
  Execute each section in its corresponding SSIS Task, not as one
  complete script.

===============================================================================
SSIS VARIABLES AND PARAMETERS
===============================================================================

User::batch_id
    SSIS Variable Type: Int64
    SQL Server Type: INT
    Purpose: Identifies the current ETL batch.
    Created in stg_load_execute and passed to child packages.

User::error_message
    SSIS Variable Type: String
    SQL Server Type: NVARCHAR
    Purpose: Stores the operation error or result message.

User::is_success
    SSIS Variable Type: Int64
    SQL Server Type: INT
    Values:
        1  = Success
       -1  = Failure

User::row_counts
    SSIS Variable Type: Int64 if SQL column no_rows is BIGINT;
                        Int64 if SQL column no_rows is INT.
    Purpose: Stores the number of rows affected or loaded.

$Package::table_name
    SSIS Package Parameter Type: String
    Purpose: Contains the name of the staging table handled by
    the current child package.

===============================================================================
*/


