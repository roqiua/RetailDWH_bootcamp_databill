/*
===============================================================================
PART 4: EXECUTION FLOW AND FAILURE HANDLING
===============================================================================

PARENT PACKAGE: stg_load_execute
--------------------------------
1. Log Batch Start.
2. Execute each child table package.
3. Log Batch End.

CHILD PACKAGE: EACH STAGING TABLE
---------------------------------
1. Execute the truncate stored procedure.
2. On success:
       Execute Truncate Log Success.
3. On failure:
       Execute Truncate Log Fail.
       Do not continue with the insert for this table.
4. If truncate succeeds, execute the data load.
5. On successful load:
       Execute Insert Log Success.
       Optionally execute Overwrite Log Success.
6. On load failure:
       Execute Insert Log Fail.

FAILURE POLICY
--------------
- A failed table should not prevent other independent table packages
  from running if that is the intended design.
- Configure the parent package precedence constraints accordingly.
- A failure in a child package should still be reflected in
  dbo.etl_execution_log so that Log Batch End can detect it.
- Ensure failure logging runs before the child package finishes.
- If a logging task itself fails, the batch status logic may not see
  the original failure. Consider handling logging failures separately.

===============================================================================
*/
